"""Fail-closed provenance and record validation for new benchmark runs.

Historical CSVs may be inventoried, but are never retroactively certified as
having been generated by the current code or environment.
"""

from __future__ import annotations

import hashlib
import importlib.metadata
import json
import math
import os
import platform
import subprocess
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

from shared.paths import ROOT
MANIFEST = "experiment_manifest.json"
PRIMARY_FILES = (
    "algorithm_benchmark_raw_runs.csv",
    "algorithm_benchmark_validation.csv",
    "algorithm_benchmark_convergence.csv",
)


def digest(value: object) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, allow_nan=False).encode()).hexdigest()


def file_hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def environment() -> dict:
    packages = {}
    for name in ("numpy", "scipy", "pymoo", "PyYAML"):
        packages[name] = importlib.metadata.version(name)
    return {"python": platform.python_version(), "platform": platform.platform(),
            "packages": packages,
            "threads": {key: os.environ.get(key) for key in
                        ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS")}}


def protocol(cfg: dict, specs: list) -> dict:
    return {
        "global": {key: cfg["global"][key] for key in
                   ("runs", "pop_size", "evaluation_budget", "seed_base")},
        "problems": cfg["problems"],
        "algorithms": [asdict(spec) for spec in specs],
        "statistics": cfg.get("statistics", {}),
        "initialization": "common numpy.default_rng(seed).uniform warm start",
        "reference_front": "problem.pareto_front; Das-Dennis H=200/20/6 for M=2/3/5 unless configured",
        "hypervolume_reference": "max(reference_front, axis=0) + 0.1",
        "budget_accounting": "v2: includes RNSGA2 aspiration-point objective evaluations",
    }


def make_manifest(cfg: dict, specs: list) -> dict:
    sources = sorted([*ROOT.joinpath("src").rglob("*.py"),
                      ROOT / "requirements.txt", ROOT / "pyproject.toml"])
    hashes = {path.relative_to(ROOT).as_posix(): file_hash(path) for path in sources}
    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=ROOT, text=True).strip())
    except (OSError, subprocess.CalledProcessError):
        commit, dirty = None, None
    return {"schema": 1, "kind": "captured_before_execution",
            "created_utc": datetime.now(timezone.utc).isoformat(),
            "protocol": protocol(cfg, specs), "source_hashes": hashes,
            "environment": environment(), "git_commit": commit, "git_dirty": dirty,
            "artifacts": {}}


def assert_compatible(saved: dict, current: dict) -> None:
    if saved.get("schema") != 1 or saved.get("kind") != "captured_before_execution":
        raise ValueError("No execution-time provenance; historical inventory cannot authorize resume/reuse")
    for field in ("protocol", "source_hashes", "environment"):
        if saved.get(field) != current.get(field):
            raise ValueError(f"Benchmark {field} changed; use a new output directory")


def write_manifest(out_dir: Path, manifest: dict) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / MANIFEST
    temporary = path.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def checkpoint_manifest(out_dir: Path, manifest: dict) -> None:
    manifest["artifacts"] = {name: file_hash(out_dir / name) for name in PRIMARY_FILES}
    write_manifest(out_dir, manifest)


def prepare_manifest(out_dir: Path, current: dict, *, resume: bool = False) -> dict:
    if not resume:
        if (out_dir / MANIFEST).exists() or any((out_dir / name).exists() for name in PRIMARY_FILES):
            raise ValueError(f"Output already contains research evidence: {out_dir}. Use --out-dir with a new directory")
        write_manifest(out_dir, current)
        return current
    path = out_dir / MANIFEST
    if not path.exists():
        raise ValueError("Missing execution-time manifest. Preserve historical outputs and use a new --out-dir")
    saved = json.loads(path.read_text(encoding="utf-8"))
    assert_compatible(saved, current)
    artifacts = saved.get("artifacts", {})
    for name in PRIMARY_FILES:
        target = out_dir / name
        if name in artifacts:
            if not target.exists() or file_hash(target) != artifacts[name]:
                raise ValueError(f"Checkpoint integrity mismatch: {name}; preserve files for inspection")
        elif target.exists():
            raise ValueError(f"Uncommitted checkpoint file: {name}")
    return saved


def problem_label(problem: dict) -> str:
    if "label" in problem:
        return str(problem["label"])
    name = str(problem["name"])
    return f"{name}_m{problem['n_obj']}" if name.lower().startswith(("dtlz", "wfg")) else name


def validate_records(raw: list[dict], validation: list[dict], cfg: dict, specs: list,
                     *, require_complete: bool = False, convergence: list[dict] | None = None) -> None:
    """Check identity, seeds, dimensions, budgets and matching diagnostic rows.

    An entire problem is the atomic resumable unit; partial problems are rejected.
    Collapsed/invalid outcomes remain evidence and are not silently discarded here.
    """
    names = {spec.name: spec.runner for spec in specs}
    problems = {problem_label(p): p for p in cfg["problems"]}
    if len(problems) != len(cfg["problems"]):
        raise ValueError("Problem labels must be unique")
    runs = int(cfg["global"]["runs"])
    budget = int(cfg["global"]["evaluation_budget"])
    seed_base = int(cfg["global"]["seed_base"])
    seen = {}
    for row in raw:
        label, name, idx = str(row["problem"]), str(row["algorithm"]), int(row["run_idx"])
        key = label, name, idx
        if key in seen or label not in problems or name not in names or not 0 <= idx < runs:
            raise ValueError(f"Duplicate or unexpected run key: {key}")
        p = problems[label]
        if (int(row["seed"]) != seed_base + idx or int(row["evaluation_budget"]) != budget
                or not 0 < int(row["n_eval"]) <= budget
                or int(row["n_var"]) != int(p["n_var"])
                or int(row["n_obj"]) != int(p.get("n_obj", 2))
                or row["runner"] != names[name]):
            raise ValueError(f"Seed, dimensions, runner or budget mismatch: {key}")
        if str(row["valid"]).lower() == "true" and not all(math.isfinite(float(row[m])) for m in ("IGD", "HV")):
            raise ValueError(f"Non-finite metrics: {key}")
        seen[key] = row
    expected = {(label, name, idx) for label in problems for name in names for idx in range(runs)}
    if require_complete and set(seen) != expected:
        raise ValueError(f"Incomplete run set: {len(seen)}/{len(expected)} records")
    for label in problems:
        keys = {k for k in seen if k[0] == label}
        if keys and keys != {k for k in expected if k[0] == label}:
            raise ValueError(f"Cannot resume partially completed problem: {label}")
    diagnostics = set()
    for row in validation:
        key = str(row["problem"]), str(row["algorithm"]), int(row["run_idx"])
        if key in diagnostics or key not in seen:
            raise ValueError(f"Duplicate or unexpected validation record: {key}")
        original = seen[key]
        for field in ("seed", "n_eval", "evaluation_budget", "validation_status", "valid", "front_size"):
            if str(row[field]).lower() != str(original[field]).lower():
                raise ValueError(f"Validation mismatch for {field}: {key}")
        diagnostics.add(key)
    if diagnostics != set(seen):
        raise ValueError("Missing validation records")
    checkpoints = set()
    for row in convergence or []:
        key = str(row["problem"]), str(row["algorithm"]), int(row["run_idx"])
        fraction = float(row["checkpoint_fraction"])
        checkpoint = (*key, fraction)
        if key not in seen or checkpoint in checkpoints or not 0 < fraction <= 1:
            raise ValueError(f"Unexpected or duplicate convergence record: {checkpoint}")
        if (int(row["seed"]) != int(seen[key]["seed"])
                or not 0 < int(row["target_evaluations"]) <= int(row["n_eval"]) <= budget
                or not all(math.isfinite(float(row[m])) for m in ("IGD", "HV"))):
            raise ValueError(f"Invalid convergence record: {checkpoint}")
        checkpoints.add(checkpoint)
    if convergence is not None and {key[:3] for key in checkpoints} != set(seen):
        raise ValueError("Missing convergence trajectories")
